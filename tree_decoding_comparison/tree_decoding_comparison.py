def summarize_candidate_metadata(
    metadata: List[Dict[str, Any]],
) -> Dict[str, float]:
    """Summarize the budget composition for one generation method."""
    if not metadata:
        return {}

    summary = {}
    for key in (
        "tree_leaf_count",
        "tree_internal_node_count",
        "tree_output_node_count",
        "filler_count",
        "total_count",
    ):
        values = [float(item.get(key, 0)) for item in metadata]
        summary[f"{key}_mean"] = float(np.mean(values))
        summary[f"{key}_min"] = float(np.min(values))
        summary[f"{key}_max"] = float(np.max(values))
    return summary


def validate_experiment_args(args: argparse.Namespace) -> None:
    """Fail early on configurations that cannot define a fair comparison."""
    for flag, value in (
        ("--num-samples", args.num_samples),
        ("--max-tokens", args.max_tokens),
        ("--max-model-len", args.max_model_len),
        ("--tensor-parallel-size", args.tensor_parallel_size),
        ("--calibration-n", args.calibration_n),
        ("--calibration-max-tokens", args.calibration_max_tokens),
    ):
        if value < 1:
            raise ValueError(f"{flag} must be positive, got {value}.")
    if args.n < 1:
        raise ValueError(f"--n must be positive, got {args.n}.")
    if args.branching_factor < 2:
        raise ValueError(
            "--branching-factor must be at least 2 for tree decoding.")
    if args.max_tree_depth < 0:
        raise ValueError("--max-tree-depth must be non-negative.")
    if args.min_seg_length < 0:
        raise ValueError("--min-seg-length must be non-negative.")
    if not 0.0 <= args.random_branch_probability <= 1.0:
        raise ValueError("--random-branch-probability must be in [0, 1].")
    if not 0.0 <= args.calibration_quantile <= 1.0:
        raise ValueError("--calibration-quantile must be in [0, 1].")
    if not 0.0 < args.top_p <= 1.0:
        raise ValueError("--top-p must be in (0, 1].")
    if args.top_k < -1:
        raise ValueError("--top-k must be -1, 0, or a positive integer.")
    if not 0.0 < args.gpu_memory_utilization <= 1.0:
        raise ValueError("--gpu-memory-utilization must be in (0, 1].")
    for flag, value in (
        ("--temperature", args.temperature),
        ("--entropy-threshold", args.entropy_threshold),
        ("--tau-importance", args.tau_importance),
        ("--random-branch-probability", args.random_branch_probability),
        ("--calibration-quantile", args.calibration_quantile),
    ):
        if not math.isfinite(value):
            raise ValueError(f"{flag} must be finite, got {value}.")
    if args.temperature < 1e-5:
        raise ValueError(
            "--temperature must be at least 1e-5 because this experiment "
            "requires stochastic n-way sampling.")


