def last_boxed_only_string(string: str) -> Optional[str]:
    """Extract last boxed content from string."""
    idx = string.rfind("\\boxed")
    if idx < 0:
        idx = string.rfind("\\fbox")
        if idx < 0:
            return None

    i = idx
    right_brace_idx = None
    num_left_braces_open = 0
    while i < len(string):
        if string[i] == "{":
            num_left_braces_open += 1
        if string[i] == "}":
            num_left_braces_open -= 1
            if num_left_braces_open == 0:
                right_brace_idx = i
                break
        i += 1
    if right_brace_idx is None:
        return None
    return string[idx:right_brace_idx + 1]


def remove_boxed(s: str) -> str:
    """Remove boxed wrapper from string."""
    left = "\\boxed{"
    try:
        if s[:len(left)] == left and s[-1] == "}":
            return s[len(left):-1]
    except Exception:
        pass
    return s


def extract_answer(generation: str) -> Optional[str]:
    """Extract answer from generation."""
    if "\\boxed" in generation or "\\fbox" in generation:
        boxed = last_boxed_only_string(generation)
        if boxed:
            return remove_boxed(boxed)
    return None


def normalize_answer(answer: Optional[str]) -> Optional[str]:
    """Normalize answer for comparison."""
    if answer is None:
        return None
    answer = answer.strip()

    # Remove units and common patterns
    import re
    answer = re.sub(r'\\text\{.*?\}$', '', answer).strip()
    answer = re.sub(r'\\text\{', '', answer)
    answer = answer.replace('}', '')
    answer = answer.replace('{', '')
    answer = answer.replace('$', '')

    # Try to extract numerical value
    try:
        # Check if it's a number
        val = float(answer.replace(',', ''))
        if val.is_integer():
            return str(int(val))
        return str(val)
    except (ValueError, TypeError):
        pass

    return answer


def grade_answer(model_answer: Optional[str], ground_truth: str) -> bool:
    """
    Grade if model answer matches ground truth.

    Args:
        model_answer: Extracted answer from model
        ground_truth: Ground truth answer

    Returns:
        True if correct, False otherwise
    """
    if model_answer is None:
        return False

    # Normalize both answers
    norm_model = normalize_answer(model_answer)
    norm_gt = normalize_answer(ground_truth)

    if norm_model is None or norm_gt is None:
        return False

    # Direct string match
    if norm_model == norm_gt:
        return True

    # Try numerical comparison
    try:
        model_val = float(norm_model.replace(',', ''))
        gt_val = float(norm_gt.replace(',', ''))
        if abs(model_val - gt_val) < 1e-4:
            return True
    except (ValueError, TypeError):
        pass

    # Try symbolic comparison as fallback
    try:
        import sympy
        model_expr = sympy.sympify(norm_model)
        gt_expr = sympy.sympify(norm_gt)
        if sympy.simplify(model_expr - gt_expr) == 0:
            return True
    except Exception:
        pass

    return False


def evaluate_generations(generations: List[str], ground_truth: str) -> List[bool]:
    """
    Evaluate a list of generations against ground truth.

    Args:
        generations: List of generated responses
        ground_truth: Ground truth answer

    Returns:
        List of booleans indicating correctness
    """
    results = []
    for gen in generations:
        answer = extract_answer(gen)
        correct = grade_answer(answer, ground_truth)
        results.append(correct)
    return results


# ========== Threshold Calibration ==========

def collect_threshold_stats(
    llm: LLM,
    prompts: List[str],
    n: int = 5,
    temperature: float = 1.0,
    top_p: float = 1.0,
    top_k: int = -1,
    max_tokens: int = 200,
    quantile: float = 0.8,
    seed: Optional[int] = None,
) -> Tuple[float, float]:
    """
    Collect entropy and importance stats using vllm's collect_threshold_stats mode,
    then compute quantiles as thresholds.

    Args:
        llm: vLLM instance
        prompts: List of prompts for calibration
        n: Number of sequences per prompt for calibration
        temperature: Sampling temperature
        top_p: Top-p sampling parameter
        top_k: Top-k sampling parameter
        max_tokens: Max tokens for calibration (shorter than full generation)
        quantile: Quantile to use for threshold (0.8 = 80th percentile)

    Returns:
        Tuple of (entropy_threshold, tau_importance)
    """
    print("\nCollecting threshold stats...")

    all_entropies = []
    all_importances = []

    params = [
        SamplingParams(
            n=n,
            temperature=temperature,
            top_p=top_p,
            top_k=top_k,
            max_tokens=max_tokens,
            collect_threshold_stats=True,
            # The training path is entropy-only. This comparison utility opts
            # in explicitly because it still benchmarks the legacy WAAD mode.
            collect_importance_stats=True,
            seed=None if seed is None else seed + prompt_idx * n,
        )
        for prompt_idx in range(len(prompts))
    ]

    # Process prompts in one batch
    outputs = llm.generate(prompts, params)

    for output in outputs:
        for i in range(len(output.outputs)):
            result = output.outputs[i]
            if hasattr(result, 'entropy_list') and result.entropy_list:
                all_entropies.extend(result.entropy_list)
            if hasattr(result, 'importance_list') and result.importance_list:
                all_importances.extend([x for x in result.importance_list if x is not None])

    if not all_entropies or not all_importances:
        raise RuntimeError(
            "Threshold calibration did not return both entropy and WAAD "
            f"statistics (entropy={len(all_entropies)}, "
            f"waad={len(all_importances)}). Entropy+WAAD would otherwise run "
            "with a misleading fallback threshold. Ensure the custom vLLM "
            "checkout is loaded and chunked prefill is disabled.")

    entropy_threshold = float(np.quantile(all_entropies, quantile))
    tau_importance = float(np.quantile(all_importances, quantile))
    print(f"  Entropy stats: {len(all_entropies)} tokens")
    print(f"  Entropy range: [{min(all_entropies):.4f}, {max(all_entropies):.4f}]")
    print(f"  Entropy {int(quantile*100)}th percentile: {entropy_threshold:.4f}")
    print(f"  Importance stats: {len(all_importances)} tokens")
    print(f"  Importance range: [{min(all_importances):.4f}, {max(all_importances):.4f}]")
    print(f"  Importance {int(quantile*100)}th percentile: {tau_importance:.4f}")

    return entropy_threshold, tau_importance


# ========== Pass@k Calculation ==========

def compute_pass_at_k(results_per_example: List[List[bool]], k: int) -> float:
    """Compute the order-invariant pass@k candidate-pool estimator.

    For one prompt with ``n`` observed candidates and ``c`` correct answers,
    the score is ``1 - C(n-c, k) / C(n, k)``. For correlated tree leaves this
    should be read as the success probability of a uniformly chosen k-subset
    of the observed pool, rather than as an iid-policy estimator.

    Args:
        results_per_example: List where each element is a list of booleans
                            indicating correctness for that example's generations
        k: k for pass@k

    Returns:
        pass@k score
    """
    if k < 1:
        raise ValueError(f"k must be positive, got {k}.")
    if not results_per_example:
        raise ValueError("pass@k requires at least one example.")

    scores = []

    for example_idx, results in enumerate(results_per_example):
        if len(results) == 0:
            raise ValueError(
                f"Example {example_idx} has no candidates; pass@k cannot "
                "silently exclude it from the denominator.")
        n = len(results)
        if k > n:
            raise ValueError(
                f"pass@{k} requires at least {k} candidates, got {n}.")
        c = sum(bool(value) for value in results)
        miss_probability = (
            0.0 if n - c < k
            else math.comb(n - c, k) / math.comb(n, k)
        )
        scores.append(1.0 - miss_probability)

    return float(np.mean(scores)) if scores else 0.0


def compute_all_pass_k(results_per_example: List[List[bool]], max_k: int = 8) -> Dict[str, float]:
    """
    Compute pass@1 to pass@max_k.

    Args:
        results_per_example: List where each element is a list of booleans
        max_k: Maximum k to compute

    Returns:
        Dictionary with pass@k scores
    """
    pass_k_scores = {}
    for k in range(1, max_k + 1):
        pass_k_scores[f"pass@{k}"] = compute_pass_at_k(results_per_example, k)
    return pass_k_scores


# ========== Generation with vLLM ==========

def generate_base_grpo(
    llm: LLM,
    prompts: List[str],
    n: int = 8,
    temperature: float = 1.0,
    top_p: float = 1.0,
    top_k: int = -1,
    max_tokens: int = 4096,
    seed: Optional[int] = None,
) -> List[List[str]]:
    """
    Generate using base GRPO sampling (independent sampling).

    Default parameters match verl's RolloutConfig:
    - temperature: 1.0
    - top_p: 1.0
    - top_k: -1

    Args:
        llm: vLLM instance
        prompts: List of prompts
        n: Number of sequences per prompt
        temperature: Sampling temperature
        top_p: Top-p sampling parameter
        top_k: Top-k sampling parameter
        max_tokens: Max tokens to generate

    Returns:
        List where each element is a list of n generations for that prompt
    """
    sampling_params = [
        SamplingParams(
            temperature=temperature,
            max_tokens=max_tokens,
            n=n,
            top_p=top_p,
            top_k=top_k,
            seed=None if seed is None else seed + prompt_idx * n,
        )
        for prompt_idx in range(len(prompts))
    ]

    outputs = llm.generate(prompts, sampling_params)
    if len(outputs) != len(prompts):
        raise RuntimeError(
            f"Base GRPO returned {len(outputs)} prompt outputs for "
            f"{len(prompts)} prompts.")

    all_generations = []
    for prompt_idx, output in enumerate(outputs):
        gens = [o.text if o.text is not None else "" for o in output.outputs]
        if len(gens) != n:
            raise RuntimeError(
                f"Base GRPO prompt {prompt_idx} returned {len(gens)} "
                f"candidates; expected exactly {n}.")
        all_generations.append(gens)

    return all_generations


def reconstruct_tree_leaf_text(leaf: Any, seq_map: Dict[int, Any]) -> str:
    """Reconstruct one complete leaf response without discarding empty text."""
    path_texts = []
    current = leaf
    visited = set()

    while current is not None:
        seq_id = getattr(current, "seq_id", None)
        if seq_id is not None:
            if seq_id in visited:
                raise RuntimeError(f"Cycle found in tree output at seq_id={seq_id}.")
            visited.add(seq_id)

        segment = getattr(current, "tree_text", None)
        if segment is None:
            segment = getattr(current, "text", "")
        path_texts.append(segment or "")

        parent_seq_id = getattr(current, "parent_seq_id", None)
        if parent_seq_id is None:
            current = None
        elif parent_seq_id not in seq_map:
            raise RuntimeError(
                f"Tree leaf seq_id={getattr(leaf, 'seq_id', None)} refers "
                f"to missing parent_seq_id={parent_seq_id}.")
        else:
            current = seq_map[parent_seq_id]

    return "".join(reversed(path_texts))


def extract_tree_leaf_candidates(output: Any) -> Tuple[List[str], Dict[str, int]]:
    """Extract complete leaves and tree-shape metadata from one output."""
    nodes = list(output.outputs)
    seq_map = {}
    for node in nodes:
        seq_id = getattr(node, "seq_id", None)
        if seq_id is None:
            continue
        if seq_id in seq_map:
            raise RuntimeError(f"Duplicate seq_id={seq_id} in tree output.")
        seq_map[seq_id] = node
    leaf_nodes = [node for node in nodes if getattr(node, "is_leaf", None) is True]
    if not leaf_nodes:
        raise RuntimeError(
            "Tree decoding returned no nodes marked is_leaf=True. Verify that "
            f"the custom vLLM checkout is loaded from {VLLM_SOURCE_PATH!r}.")

    candidates = [
        reconstruct_tree_leaf_text(leaf, seq_map) for leaf in leaf_nodes
    ]
    shape = {
        "tree_leaf_count": len(leaf_nodes),
        "tree_internal_node_count": sum(
            getattr(node, "is_leaf", None) is False for node in nodes),
        "tree_output_node_count": len(nodes),
    }
    return candidates, shape


def generate_tree_decoding(
    llm: LLM,
    prompts: List[str],
    branch_trigger_mode: str,
    target_n: int,
    branching_factor: int = 2,
    max_tree_depth: int = 3,
    entropy_threshold: float = 1.0,
    tau_importance: Optional[float] = None,
    random_branch_probability: float = 0.2,
    min_seg_length: int = 128,
    temperature: float = 1.0,
    top_p: float = 1.0,
    top_k: int = -1,
    max_tokens: int = 4096,
    seed: Optional[int] = None,
) -> Tuple[List[List[str]], List[Dict[str, Any]]]:
    """
    Generate using Tree Decoding.

    The tree is capped at ``target_n`` complete leaves. If it produces fewer,
    the deficit is filled with fresh iid GRPO samples using identical sampling
    parameters. Duplicate and empty responses each consume one candidate slot.

    Args:
        llm: vLLM instance
        prompts: List of prompts
        branch_trigger_mode: random, entropy, or entropy_waad
        target_n: Exact number of final answer candidates per prompt
        branching_factor: Maximum branching factor for each split
        max_tree_depth: Max depth for tree
        entropy_threshold: Entropy threshold for branching
        tau_importance: Tau for importance sampling
        temperature: Sampling temperature
        top_p: Top-p sampling parameter
        top_k: Top-k sampling parameter
        max_tokens: Max tokens to generate

    Returns:
        Pair of generations and per-prompt candidate/source metadata
    """
    if branch_trigger_mode not in {"random", "entropy", "entropy_waad"}:
        raise ValueError(f"Unsupported branch trigger mode: {branch_trigger_mode!r}.")
    if target_n < 1:
        raise ValueError(f"target_n must be positive, got {target_n}.")
    if branch_trigger_mode == "entropy_waad" and tau_importance is None:
        raise ValueError("entropy_waad mode requires a numeric tau_importance.")

    tree_params = [
        SamplingParams(
            temperature=temperature,
            max_tokens=max_tokens,
            top_p=top_p,
            top_k=top_k,
            seed=(
                None if seed is None else seed + prompt_idx * target_n),
            tree_search_params=TreeSearchParams(
                enable_tree_search=True,
                entropy_threshold=entropy_threshold,
                branching_factor=branching_factor,
                max_tree_depth=max_tree_depth,
                tau_importance=(
                    tau_importance if branch_trigger_mode == "entropy_waad"
                    else None),
                min_seg_length=min_seg_length,
                branch_trigger_mode=branch_trigger_mode,
                random_branch_probability=random_branch_probability,
                max_num_leaves=target_n,
            ),
        )
        for prompt_idx in range(len(prompts))
    ]

    outputs = llm.generate(prompts, tree_params)
    if len(outputs) != len(prompts):
        raise RuntimeError(
            f"{branch_trigger_mode} tree returned {len(outputs)} prompt "
            f"outputs for {len(prompts)} prompts.")

    all_generations = []
    metadata = []
    filler_requests = []

    for prompt_idx, output in enumerate(outputs):
        leaf_generations, tree_shape = extract_tree_leaf_candidates(output)
        if len(leaf_generations) > target_n:
            raise RuntimeError(
                f"{branch_trigger_mode} tree prompt {prompt_idx} returned "
                f"{len(leaf_generations)} leaves, exceeding max_num_leaves="
                f"{target_n}. Verify that the patched vLLM is loaded.")

        all_generations.append(list(leaf_generations))
        needed = target_n - len(leaf_generations)
        prompt_metadata = {
            **tree_shape,
            "filler_count": needed,
            "total_count": len(leaf_generations),
            "candidate_sources": ["tree"] * len(leaf_generations),
        }
        metadata.append(prompt_metadata)
        if needed:
            filler_requests.append((prompt_idx, prompts[prompt_idx], needed))

    if filler_requests:
        total_missing = sum(needed for _, _, needed in filler_requests)
        print(
            f"  {branch_trigger_mode}: filling {total_missing} iid slots "
            f"across {len(filler_requests)} prompts...")
        filler_prompts = [prompt for _, prompt, _ in filler_requests]
        filler_params = []
        for prompt_idx, _, needed in filler_requests:
            filler_seed = (
                None if seed is None
                else seed + 1_000_003 + prompt_idx * target_n)
            filler_params.append(SamplingParams(
                temperature=temperature,
                max_tokens=max_tokens,
                n=needed,
                top_p=top_p,
                top_k=top_k,
                seed=filler_seed,
            ))

        filler_outputs = llm.generate(filler_prompts, filler_params)
        if len(filler_outputs) != len(filler_requests):
            raise RuntimeError(
                f"{branch_trigger_mode} filler returned {len(filler_outputs)} "
                f"prompt outputs for {len(filler_requests)} requests.")

        for filler_output, (prompt_idx, _, needed) in zip(
                filler_outputs, filler_requests):
            filler_texts = [
                completion.text if completion.text is not None else ""
                for completion in filler_output.outputs
            ]
            if len(filler_texts) != needed:
                raise RuntimeError(
                    f"{branch_trigger_mode} filler for prompt {prompt_idx} "
                    f"returned {len(filler_texts)} candidates; expected "
                    f"exactly {needed}.")
            all_generations[prompt_idx].extend(filler_texts)
            metadata[prompt_idx]["candidate_sources"].extend(
                ["grpo_filler"] * needed)
            metadata[prompt_idx]["total_count"] += needed

    for prompt_idx, (generations, prompt_metadata) in enumerate(
            zip(all_generations, metadata)):
        if len(generations) != target_n:
            raise RuntimeError(
                f"{branch_trigger_mode} prompt {prompt_idx} has "
                f"{len(generations)} final candidates; expected {target_n}.")
        if prompt_metadata["total_count"] != target_n:
            raise RuntimeError(
                f"{branch_trigger_mode} prompt {prompt_idx} metadata count "
                f"is {prompt_metadata['total_count']}; expected {target_n}.")

    return all_generations, metadata


